import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL('src/index.jsx', import.meta.url))],
  format: 'cjs',
  platform: 'browser',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime', 'react-dom', '@deepseek-ai/*'],
  target: 'es2022',
  bundle: true,
  write: false,
});
await writeFile(
  new URL('client.js', root),
  `// Generated by client/build.mjs; do not edit.\nwindow.__ModuleLoader__.load({ id: "dsh-plugin-atlas", factory: (require) => { var module = { exports: {} }; var exports = module.exports;\n${result.outputFiles[0].text}\nreturn module.exports; } });\n`,
);
